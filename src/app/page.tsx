"use client";

import dynamic from "next/dynamic";
import { useEffect, useState } from "react";
import { openWarehouse } from "@/lib/duckdb";
import { loadDashboardData, type DashboardData } from "@/lib/queries";
import type { ViewKey, Warehouse } from "@/lib/types";
import { ExecutiveView } from "@/components/ExecutiveView";
import { AttributionView } from "@/components/AttributionView";
import { HealthView } from "@/components/HealthView";

const AskView = dynamic(() => import("@/components/AskView").then((m) => m.AskView), {
  ssr: false,
});

const TABS: { key: ViewKey; label: string }[] = [
  { key: "executive", label: "Executive summary" },
  { key: "attribution", label: "Attribution" },
  { key: "health", label: "Account health" },
  { key: "ask", label: "Ask the warehouse" },
];

export default function Page() {
  const [view, setView] = useState<ViewKey>("executive");
  const [stage, setStage] = useState<string>("boot");
  const [error, setError] = useState<string | null>(null);
  const [wh, setWh] = useState<Warehouse | null>(null);
  const [data, setData] = useState<DashboardData | null>(null);

  useEffect(() => {
    let cancelled = false;
    (async () => {
      try {
        const warehouse = await openWarehouse(setStage);
        const d = await loadDashboardData(warehouse);
        if (cancelled) {
          warehouse.close();
          return;
        }
        setWh(warehouse);
        setData(d);
        setStage("ready");
      } catch (e) {
        if (!cancelled) setError((e as Error).message);
      }
    })();
    return () => {
      cancelled = true;
    };
  }, []);

  return (
    <main className="mx-auto max-w-[1200px] px-4 sm:px-6 py-6">
      <header className="mb-6">
        <div className="flex flex-wrap items-end justify-between gap-3">
          <div>
            <div className="text-xs font-semibold uppercase tracking-widest text-teal">
              Synthetic demo · hiring-manager build
            </div>
            <h1 className="mt-1 text-3xl sm:text-4xl font-semibold leading-tight">
              Quillmere Bio — Commercial Intelligence
            </h1>
            <p className="mt-1 text-sm text-muted max-w-[70ch]">
              A life-sciences tools company&apos;s revenue engine, end to end: 1,507 synthetic
              orders from 248 accounts, modeled in SQL, queried live from a DuckDB warehouse in
              this browser.
            </p>
          </div>
          <a
            href="https://github.com/haybaler/commercial-intelligence"
            target="_blank"
            rel="noreferrer"
            className="text-sm font-semibold text-teal hover:text-teal-dark"
          >
            Repo &amp; README ↗
          </a>
        </div>

        <nav className="mt-5 flex flex-wrap gap-1 border-b border-line" aria-label="Views">
          {TABS.map((t) => (
            <button
              key={t.key}
              onClick={() => setView(t.key)}
              aria-current={view === t.key ? "page" : undefined}
              className={`px-4 py-2.5 text-sm font-semibold border-b-2 -mb-px transition-colors ${
                view === t.key
                  ? "border-teal text-teal-dark"
                  : "border-transparent text-muted hover:text-ink"
              }`}
            >
              {t.label}
            </button>
          ))}
        </nav>
      </header>

      {error && (
        <div className="card border-brick/40 bg-brick/5 p-6" role="alert">
          <h2 className="font-semibold text-brick">The warehouse failed to load</h2>
          <p className="mt-1 text-sm">{error}</p>
          <p className="mt-2 text-xs text-muted">
            This app serves warehouse.duckdb and the duckdb-wasm assets same-origin; if you are
            viewing a static export, make sure data/warehouse.duckdb and vendor/duckdb/ were
            copied alongside index.html.
          </p>
        </div>
      )}

      {!error && stage !== "ready" && (
        <div className="card p-10 text-center">
          <div className="mx-auto h-6 w-6 animate-spin rounded-full border-2 border-teal border-t-transparent" aria-hidden />
          <p className="mt-4 text-sm text-muted">{stage}</p>
        </div>
      )}

      {stage === "ready" && data && (
        <>
          {view === "executive" && <ExecutiveView data={data} />}
          {view === "attribution" && <AttributionView data={data} />}
          {view === "health" && <HealthView data={data} />}
          {view === "ask" && wh && <AskView wh={wh} />}
        </>
      )}

      <footer className="mt-10 border-t border-line pt-4 pb-8 text-xs text-muted flex flex-wrap gap-x-6 gap-y-1">
        <span>All data is synthetic — generated by scripts/generate_data.py (seeded, reproducible).</span>
        <span>Models: models/*.sql → DuckDB → this page.</span>
        <span>Decisions &amp; tradeoffs: README.md.</span>
      </footer>
    </main>
  );
}
